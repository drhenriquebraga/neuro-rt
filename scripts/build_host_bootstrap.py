"""Generate the small trusted stdlib bootstrap shipped as part of the host base."""
import argparse
import base64
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = ('plugin_consent', 'plugin_manifest', 'model_paths', 'model_registry', 'install_state', 'plugin_update')


def generate(destination, root=ROOT):
    root = Path(root)
    sources = {}
    for name in FILES:
        raw = (root / 'neuro_rt' / (name + '.py')).read_bytes()
        sources[name] = (hashlib.sha256(raw).hexdigest(), base64.b64encode(raw).decode('ascii'))
    provider = (root / 'integration/update_provider.py').read_text(encoding='utf-8')
    license_notice = ''.join(('# ' + line if line else '#') + '\n' for line in
        (root / 'LICENSE').read_text(encoding='utf-8').splitlines())
    Path(destination).write_text('# Generated by NEURO_RT/scripts/build_host_bootstrap.py.\n'
        '# Sources are pinned to the base host release, never loaded from a downloaded ZIP.\n'
        + '# Original NeuroRT license follows and must accompany redistribution.\n'
        + license_notice + '\nSOURCES = ' + repr(sources) + '\n\n' + provider
        + '\n\nINSTALL_UI_SCRIPT = ' + repr((root / 'web/plugin-update.js').read_text(encoding='utf-8'))
        + '\nINSTALL_UI_CATALOG = ' + repr(json.loads((root / 'web/plugin-update-i18n.json').read_text(encoding='utf-8')))
        + '\n', encoding='utf-8')
    return Path(destination)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination', type=Path)
    print(generate(parser.parse_args().destination))
